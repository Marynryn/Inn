/**
 * Сколько слов в главе. Считается один раз при сохранении и ложится в базу:
 * трекеру прогресса нужны длины всех глав разом, а тянуть ради этого весь
 * текст было бы слишком дорого.
 *
 * Слово — цепочка букв и цифр, дефис и апостроф внутри не рвут её:
 * «кто-нибудь» — одно слово, а не два. Знаки препинания и теги не в счёт.
 */
export function countWords(html: string): number {
  const text = html
    .replace(/<[^>]*>/g, ' ')
    .replace(/&[a-z#0-9]+;/gi, ' ')
  return text.match(/[\p{L}\p{N}]+(?:[-'’][\p{L}\p{N}]+)*/gu)?.length ?? 0
}
