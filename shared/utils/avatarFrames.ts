/**
 * Рамка вокруг аватарки — картинка с прозрачной серединой. Аватарка остаётся
 * кругом и своего размера, рамка ложится поверх и выходит за его края: так
 * человек с рамкой не выглядит мельче человека без неё.
 *
 * Набор рамок живёт в базе, а не в коде: рамки раздаются на ивентах, и новая
 * рамка не должна требовать выкатки сайта.
 */
export type AvatarFrame = {
  id: number
  name: string
  /** Картинка рамки. */
  url: string
  /** Доля картинки, которую занимает дырка под аватарку: 0.72 значит «аватарка
   *  вписана в 72% ширины». Из неё считается, насколько раздуть рамку вокруг
   *  круга — у разных художников дырка разного размера. */
  fit: number
}

/**
 * Рамка в списке выбора: когда досталась и досталась ли вообще. Не выиграна —
 * состояние хозяйки сайта: ей показывается весь каталог, чтобы примерить рамку
 * на живой аватарке раньше, чем та кому-то достанется.
 */
export type OwnedFrame = AvatarFrame & { grantedAt: string | null; owned: boolean }

/** Дырка под аватарку у большинства венков — примерно две трети картинки. */
export const FRAME_FIT_DEFAULT = 0.72

/** Меньше половины — аватарка утонет в рамке, больше 0.95 — рамки не видно. */
export const FRAME_FIT_MIN = 0.4
export const FRAME_FIT_MAX = 0.95

export const FRAME_NAME_MAX = 40

/**
 * Рамка — картинка вчетверо крупнее аватарки: у неё мелкие детали по кругу, и
 * на 256 пикселях они превращаются в кашу. Вес поэтому тоже выше.
 */
export const MAX_FRAME_SIDE = 1024
export const MAX_FRAME_BYTES = 600 * 1024

/**
 * Насколько кольцо рамки заходит на аватарку — долей от собственной толщины.
 * Ноль: внутренний край кольца ровно по краю аватарки, и между ними остаётся
 * видна кромка фотографии — оправа, надетая впритык. Половина: кольцо кроет эту
 * кромку собой, и аватарка уходит под рамку, а не лежит рядом с ней.
 */
export const FRAME_OVERLAP = 0.5

/**
 * Во сколько раз картинка рамки шире аватарки, на которую ложится. Дырка
 * занимает fit ширины картинки, кольцо — по (1-fit)/2 с каждой стороны; чтобы
 * оно зашло внутрь на долю FRAME_OVERLAP своей толщины, картинку берём во
 * столько раз крупнее. При FRAME_OVERLAP = 0 это привычное 1/fit.
 */
export const frameScale = (fit: number) => {
  const f = clampFit(fit)
  return 1 / (f + FRAME_OVERLAP * (1 - f))
}

export const clampFit = (fit: number) =>
  Math.min(FRAME_FIT_MAX, Math.max(FRAME_FIT_MIN, Number(fit) || FRAME_FIT_DEFAULT))
