export const BOARD_MAP_IDS = Object.keys(BOARD_MAPS) as BoardMapId[];
export const isBoardMapId = (v: unknown): v is BoardMapId =>
  typeof v === "string" && Object.hasOwn(BOARD_MAPS, v);

export const boardLast = (map: BoardMap) => map.cells.length - 1;

/** Куда перебрасывает клетка — или null, если она никуда не ведёт. Прыжок
 *  не выходит за старт и финиш. По нему же рисуются стрелки на карте. */
export function jumpTarget(map: BoardMap, i: number): number | null {
  const e = map.cells[i]?.effect;
  if (e?.kind === "forward") return Math.min(i + e.n, boardLast(map));
  if (e?.kind === "back") return Math.max(i - e.n, 0);
  return null;
}

export function effectLabel(e: BoardEffect): string {
  switch (e.kind) {
    case "forward":
      return `вперёд на ${e.n}`;
    case "back":
      return `назад на ${e.n}`;
    case "skip":
      return "пропуск хода";
    case "again":
      return "ещё бросок";
    default:
      return "";
  }
}

