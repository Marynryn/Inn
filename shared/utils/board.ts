/**
 * Настольная игра по карте: фишки идут по клеткам, кубик бросает сервер. Здесь
 * то, что нужно и серверу, и странице: карты, их клетки и охотники, эффекты
 * клеток и то, как выглядит комната для игрока.
 *
 * Карт две: первый том и продолжение — второй и третий. Карту выбирают, когда
 * накрывают стол, и все партии за этим столом идут по ней.
 */

/** Что делает клетка, когда на неё встали. Эффект срабатывает один раз:
 *  клетка, куда отбросило, своего эффекта уже не даёт — иначе две клетки
 *  могли бы гонять фишку друг к другу без конца. */
export type BoardEffect =
  | { kind: "none" }
  | { kind: "forward"; n: number }
  | { kind: "back"; n: number }
  | { kind: "skip" }
  | { kind: "again" };

