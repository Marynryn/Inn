/**
 * Кто ходит по карте сам, вне очереди игроков: раз за круг, когда все
 * сходили. У каждого свой нрав:
 *
 * - skinner — идёт на 1–3 клетки к ближайшему игроку, вперёд или назад, и
 *   отбрасывает того, на чьей клетке закончил ход (или кто сам к нему пришёл);
 * - toren — охотится так же, но пойманного обирает: крадёт карточку навыка,
 *   а с пустыми руками отбрасывает;
 * - fae — не охотятся, а проказничают: садятся на клетку — на чью-нибудь или
 *   просто так — и стоящему там дарят навык, превращают его карточку в
 *   цветы или засыпают лавиной;
 * - army — охотится, как Скиннер: идёт к ближайшему игроку и отбрасывает
 *   того, на чьей клетке остановилась.
 *
 * Ходят они только по своему участку карты, zone, и охотятся только на тех,
 * кто на нём стоит.
 */
export type BoardHunterKind = "skinner" | "toren" | "fae" | "army";

export type BoardHunterDef = {
  kind: BoardHunterKind;
  name: string;
  /** Участок карты, клетки с from по to включительно. */
  zone: [number, number];
  /** Выходит, когда кто-то из игроков дошёл до этой клетки. */
  wakesAt: number;
  /** Где появляется. */
  start: number;
  /** Строчка в журнал, когда вышел. */
  wakeNote: string;
  /** Подпись в легенде под картой и подсказка на фишке. */
  legend: string;
  /** Фигурка на карте — живописная, из портретов персонажей. Нет — тень с глазами. */
  token?: string;
};

/** Где охотник сейчас; null — ещё не вышел или уже ушёл. */
export type BoardHunter = { kind: BoardHunterKind; at: number | null };

