<script setup lang="ts">
/**
 * Текст главы — серверный компонент («остров»). Обычный компонент рисует текст
 * на сервере и вдобавок кладёт его в данные страницы, чтобы браузер мог
 * «оживить» разметку, — и текст ехал дважды: разметкой и в __NUXT_DATA__.
 * Остров браузер не оживляет, он берёт готовую разметку со страницы, так что
 * в данных остаётся только его адрес. При переходе между главами браузер
 * запрашивает остров у сервера сам.
 */
const props = defineProps<{ id: string }>()

const { data } = await useFetch(`/api/chapters/${encodeURIComponent(props.id)}`, {
  query: { text: 1 },
  pick: ['contentHtml'],
})
</script>

<template>
  <div v-html="data?.contentHtml || '<p><em>Текст главы загружается...</em></p>'" />
</template>
